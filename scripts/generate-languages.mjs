// Writes src/daemon/web/languages.generated.ts from the grammars shiki bundles.
//
// highlight.ts used to reach 40 extensions from a table someone typed, so a
// .proto file rendered as plain text next to a .ts file that did not. Shiki
// ships 242 grammars and most of them carry the extensions they belong to, so
// the list was already in the tree; nobody had read it.
//
// Two things decide an extension here, in order. A language whose id or alias
// is the extension wins outright: `ts` is an alias of typescript, and no
// grammar's own fileTypes can outvote that. Otherwise the extension goes to
// the one grammar that claims it, and an extension two grammars claim is left
// out for a person to settle in DECIDED_BY_EXTENSION.
//
// The id rule is not decoration. The typescript, python, go, sql and php
// grammars carry no fileTypes at all, while hack claims `.php` and plsql
// claims `.sql`; reading fileTypes alone would hand the two commonest
// extensions in the tree to the wrong languages.
//
// Run: npm run languages

import { writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { bundledLanguagesInfo } from 'shiki'

const require_ = createRequire(import.meta.url)

/** Lowercased, with any leading dot dropped, which is how languageFor asks. */
function normalise(fileType) {
  return String(fileType).toLowerCase().replace(/^\./, '')
}

// Every id and alias, which is the half of the answer that needs no grammar.
const byIdOrAlias = new Map()
for (const info of bundledLanguagesInfo) {
  byIdOrAlias.set(info.id, info.id)
  for (const alias of info.aliases ?? []) byIdOrAlias.set(alias, info.id)
}

// What each grammar says it covers.
//
// Only the grammar named for the language it came from. A language module
// exports its embedded dependencies alongside its own grammar — php ships ten,
// including javascript and sql — and counting those made every host language
// look like it claimed its guests' extensions.
const claims = new Map()
for (const info of bundledLanguagesInfo) {
  const exported = (await import(`@shikijs/langs/${info.id}`)).default
  const grammars = Array.isArray(exported) ? exported : [exported]
  const own = grammars.find((grammar) => grammar.name === info.id)
  if (!own) continue

  for (const fileType of own.fileTypes ?? []) {
    const extension = normalise(fileType)
    if (!claims.has(extension)) claims.set(extension, new Set())
    claims.get(extension).add(info.id)
  }
}

const resolved = new Map()
const contested = []
const decidedById = []

for (const [extension, languages] of claims) {
  const byId = byIdOrAlias.get(extension)

  if (byId !== undefined) {
    resolved.set(extension, byId)
    if (!(languages.size === 1 && languages.has(byId))) {
      decidedById.push(`${extension} -> ${byId}, over ${[...languages].sort().join(', ')}`)
    }
    continue
  }

  if (languages.size === 1) {
    resolved.set(extension, [...languages][0])
    continue
  }

  contested.push(`${extension} -> ${[...languages].sort().join(', ')}`)
}

// An id or alias nothing claimed. `py`, `rs` and `kt` arrive here, because
// their grammars carry no fileTypes at all.
for (const [extension, language] of byIdOrAlias) {
  if (!resolved.has(extension)) resolved.set(extension, language)
}

// Quoted the way prettier would leave them, so the generated file passes
// `format:check` without anyone reformatting a file they are told not to edit.
// Unicode aware, because shiki bundles wenyan and `文言` is a valid identifier.
// An ASCII test quotes it and prettier takes the quotes straight back off.
const IDENTIFIER = /^[$_\p{ID_Start}][$\p{ID_Continue}]*$/u

const rows = [...resolved]
  .sort(([a], [b]) => (a < b ? -1 : 1))
  .map(([extension, language]) => {
    const key = IDENTIFIER.test(extension) ? extension : `'${extension}'`
    return `  ${key}: '${language}',`
  })
  .join('\n')

const { version } = require_('shiki/package.json')

const file = `// Generated by scripts/generate-languages.mjs from shiki@${version}.
// Do not edit. Run \`npm run languages\` after upgrading shiki.
//
// Every extension shiki can answer for, minus the ones two grammars claim.
// DECIDED_BY_EXTENSION in highlight.ts is read first and overrides anything here.

import type { BundledLanguage } from 'shiki'

export const GENERATED_BY_EXTENSION: Record<string, BundledLanguage> = {
${rows}
}
`

writeFileSync(new URL('../src/daemon/web/languages.generated.ts', import.meta.url), file)

process.stdout.write(`wrote ${resolved.size} extensions from shiki@${version}\n`)

if (decidedById.length > 0) {
  process.stdout.write(`\n${decidedById.length} decided by id over a grammar that claimed them:\n`)
  for (const line of decidedById.sort()) process.stdout.write(`  ${line}\n`)
}

if (contested.length > 0) {
  process.stdout.write(`\n${contested.length} left out, claimed by more than one grammar:\n`)
  for (const line of contested.sort()) process.stdout.write(`  ${line}\n`)
  process.stdout.write(`\nAdd any of these to DECIDED_BY_EXTENSION in highlight.ts to decide it.\n`)
}
